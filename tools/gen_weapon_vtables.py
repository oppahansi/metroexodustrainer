"""Generate the C# tables of vtable RVAs the trainer uses to recognize game objects.

- MagazinedWeaponVtables: firearm classes that really derive from weapon_magazined.
- AmmoItemVtables: weapon_ammo (reserve ammo stack) items.
- NpcVtables: entities of classes derived from base_npc (humans, monsters).
The trainer identifies objects by their vtable and only writes class-specific fields into matching objects.

Usage: python gen_weapon_vtables.py <exe> <symbols.tsv> <output .cs>
Needs symbols.tsv from dump_symbols.py. Output is build-specific (RVAs of the given exe).
"""
import re
import sys

from dump_types import Pdb, TAG, TI_SYMTAG, TI_TYPEID

# Entities of a weapon class are instances of object_manager_hud<X, X_hud_item>::object_hud.
AMMO_RE = re.compile(r"^uobject_t<weapon_ammo,\d+,\d+>::`vftable'$")
NPC_RE = re.compile(r"^uobject_t<(\w+),\d+,\d+>::`vftable'$")
VTABLE_RE = re.compile(r"^uobject_t<object_manager_hud<(\w+),\1_hud_item>::object_hud,\d+,\d+>::`vftable'$")


# Device classes the trainer recognizes by vtable (name of the generated C# class -> game class).
DEVICES = {
    "GasmaskVtables": "gasmask",
    "ChargerVtables": "charger",
    "NightVisionVtables": "nightvision",
    "HellbreathVtables": "weapon_hellbreath",
}


def derives_from(pdb, tid, target, depth=0):
    if depth > 12:
        return False
    for child in pdb.children(tid):
        if pdb.info(child, TI_SYMTAG) != TAG["BaseClass"]:
            continue
        base = pdb.info(child, TI_TYPEID)
        if pdb.name(base) == target or derives_from(pdb, base, target, depth + 1):
            return True
    return False


def main(exe, symbols, out_path, profile_path=None):
    pdb = Pdb(exe)
    found = {}
    ammo = []
    npc_candidates = {}
    for line in open(symbols, encoding="utf-8", errors="replace"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 4 or parts[2] != "7":
            continue
        name = parts[3].strip(chr(9) + chr(0) + chr(32))
        if AMMO_RE.match(name):
            ammo.append(int(parts[0], 16))
        n = NPC_RE.match(name)
        if n:
            npc_candidates.setdefault(n.group(1), []).append(int(parts[0], 16))
        m = VTABLE_RE.match(name)
        if m:
            found.setdefault(m.group(1), []).append(int(parts[0], 16))

    rows = []
    for cls, rvas in sorted(found.items()):
        tid = pdb.find(cls)
        if tid is not None and (cls == "weapon_magazined" or derives_from(pdb, tid, "weapon_magazined")):
            rows.extend((cls, rva) for rva in rvas)

    pneumo = []
    for cls, rva in rows:
        tid = pdb.find(cls)
        if cls == "weapon_pneumo" or (tid is not None and derives_from(pdb, tid, "weapon_pneumo")):
            pneumo.append((cls, rva))
    devices = {out: sorted(found.get(cls, [])) for out, cls in DEVICES.items()}

    npc = []
    for cls, rvas in sorted(npc_candidates.items()):
        tid = pdb.find(cls)
        if cls != "player_new" and tid is not None and (cls == "base_npc" or derives_from(pdb, tid, "base_npc")):
            npc.extend((cls, rva) for rva in rvas)

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated> by tools/gen_weapon_vtables.py for MetroExodus.exe 2.0.1.1. Do not edit.\n")
        f.write("namespace MetroExodusTrainer.Core.Generated;\n\n")
        f.write("/// <summary>Vtable RVAs of weapon classes that derive from weapon_magazined.</summary>\n")
        f.write("public static class MagazinedWeaponVtables\n{\n")
        f.write("    public static HashSet<long> Rvas { get; internal set; } =\n    [\n")
        for cls, rva in rows:
            f.write(f"        0x{rva:X}, // {cls}\n")
        f.write("    ];\n}\n\n")
        f.write("/// <summary>Vtable RVAs of weapon_ammo (reserve ammo stack) items.</summary>\n")
        f.write("public static class AmmoItemVtables\n{\n")
        f.write("    public static HashSet<long> Rvas { get; internal set; } =\n    [\n")
        for rva in sorted(ammo):
            f.write(f"        0x{rva:X},\n")
        f.write("    ];\n}\n\n")
        f.write("/// <summary>Vtable RVAs of entities that derive from base_npc (humans and monsters).</summary>\n")
        f.write("public static class NpcVtables\n{\n")
        f.write("    public static HashSet<long> Rvas { get; internal set; } =\n    [\n")
        for cls, rva in sorted(npc, key=lambda r: r[1]):
            f.write(f"        0x{rva:X}, // {cls}\n")
        f.write("    ];\n}\n")
        f.write("\n/// <summary>Vtable RVAs of firearms that derive from weapon_pneumo (air pressure weapons).</summary>\n")
        f.write("public static class PneumoWeaponVtables\n{\n    public static HashSet<long> Rvas { get; internal set; } =\n    [\n")
        for cls, rva in pneumo:
            f.write(f"        0x{rva:X}, // {cls}\n")
        f.write("    ];\n}\n")
        for out, rvas in devices.items():
            f.write(f"\n/// <summary>Vtable RVAs of {DEVICES[out]} entities.</summary>\n")
            f.write(f"public static class {out}\n{{\n    public static HashSet<long> Rvas {{ get; internal set; }} =\n    [\n")
            for rva in rvas:
                f.write(f"        0x{rva:X},\n")
            f.write("    ];\n}\n")
    if profile_path:
        import json
        import pefile
        pe = pefile.PE(exe)
        profile = {
            "timeDateStamp": f"0x{pe.FILE_HEADER.TimeDateStamp:08X}",
            "vtables": {
                "MagazinedWeaponVtables": sorted({rva for _, rva in rows}),
                "AmmoItemVtables": sorted(set(ammo)),
                "NpcVtables": sorted({rva for _, rva in npc}),
                "PneumoWeaponVtables": sorted({rva for _, rva in pneumo}),
                **{out: sorted(set(rvas)) for out, rvas in devices.items()},
            },
        }
        with open(profile_path, "w", encoding="utf-8") as pf:
            json.dump(profile, pf, indent=1)
        print(f"wrote profile {profile_path}")
    print(f"{len(npc)} npc vtables for {len({c for c, _ in npc})} classes")
    print(f"{len(rows)} vtables for {len({c for c, _ in rows})} classes ({len(found)} weapon-like classes seen)")
    skipped = sorted(set(found) - {c for c, _ in rows})
    print("not derived from weapon_magazined:", ", ".join(skipped))


if __name__ == "__main__":
    main(*sys.argv[1:5])
